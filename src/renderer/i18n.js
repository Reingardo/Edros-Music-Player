  const DICTS = { es, en };

  function make(lang) {
    const d = DICTS[lang] || es;
    return (key, vars = {}) => {
      if (!key) return '';
      const v = d[key] ?? es[key];
      if (v === undefined) return '';
      if (typeof v === 'function') return v(vars);
      if (Array.isArray(v)) return v;
      return v.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ''));
    };
  }

  window.I18N = { make, langs: Object.keys(DICTS), dicts: DICTS };
